import React, { useState } from 'react';
import {
  stampKind, stampLabel, stampClass, formatDuration, formatTokens,
  visibleOps, hasPartial, shareable, type Receipt,
} from './receiptModel';

interface Props { receipt: Receipt; onReviewDiff?: () => void; onUndo?: () => void; onShare?: () => void; onNext?: () => void; }

export function OutcomeReceipt({ receipt, onReviewDiff, onUndo, onShare, onNext }: Props) {
  const kind = stampKind(receipt.status);
  const ops = visibleOps(receipt);
  const [confirmShare, setConfirmShare] = useState(false);
  const handleShare = () => {
    // Explicit field-level sanitisation: only structured fields, never free-text (objective/nextAction).
    const safe = [
      `Pandesh Outcome Receipt`,
      `Status: ${receipt.headline}`,
      `Operations: ${receipt.operations.map((o) => `${o.count} ${o.label}`).join(', ') || 'none recorded'}`,
      receipt.verifiedOutputs.length ? `Verified outputs: ${receipt.verifiedOutputs.map((v) => `${v.label} (${v.level})`).join('; ')}` : null,
      receipt.partialOrFailed.length ? `Not completed: ${receipt.partialOrFailed.map((p) => `${p.status} - ${p.reason}`).join('; ')}` : null,
      `Model: ${receipt.model ?? '—'} (${receipt.provider ?? '—'})`,
      `Duration: ${formatDuration(receipt.durationMs)}`,
      `Approvals used: ${receipt.approvalsUsed}`,
      receipt.independentlyReviewed ? 'Independently reviewed: yes' : null,
      'Generated by Pandesh. Free-text fields (objective, next action) excluded from share.',
    ].filter(Boolean).join('\n');
    if (onShare) onShare(); else if (navigator.clipboard) navigator.clipboard.writeText(safe);
    setConfirmShare(false);
  };
  return (
    <div className="receipt" role="article" aria-label={`Outcome receipt: ${receipt.objective}`}>
      <div className="stamp-row">
        <span className={`stamp ${stampClass(kind)}`}>{stampLabel(kind)}</span>
        <span className="muted" style={{ fontSize: '11px', fontFamily: 'var(--font-mono)' }}>
          {receipt.completedAt ? new Date(receipt.completedAt).toLocaleString() : ''} · {formatDuration(receipt.durationMs)}
        </span>
      </div>
      <div className="objective serif">{receipt.objective}</div>
      {receipt.nextAction && <div className="muted" style={{ fontSize: '13px', marginBottom: '12px' }}>{receipt.nextAction}</div>}

      <div className="h3">Operations performed</div>
      <div className="ops">
        {ops.map((o) => (
          <div className="op" key={o.label}><span className="n">{o.count}</span> {o.label}</div>
        ))}
        {ops.length === 0 && <div className="muted" style={{ fontSize: '13px' }}>No operations recorded.</div>}
      </div>
      <div className="muted" style={{ fontSize: '10px', fontFamily: 'var(--font-mono)', marginBottom: '8px' }}>
        Counts are tool-observed. "files written" counts write calls, not necessarily committed changes.
      </div>

      {receipt.artifacts.length > 0 && (
        <>
          <div className="h3">Artifacts</div>
          <div className="artifacts">
            {receipt.artifacts.map((a, i) => (
              <span className="artifact" key={i}>{a.kind === 'file' ? '{}' : ' '} {a.path.split(/[\\/]/).pop()}</span>
            ))}
          </div>
        </>
      )}

      {receipt.verifiedOutputs.length > 0 && (
        <>
          <div className="h3">Verified outputs</div>
          {receipt.verifiedOutputs.map((v, i) => (
            <div className="evidence-row" key={i}><span>{v.label}</span><span className={`level ${v.level}`}>{v.level}</span></div>
          ))}
          <div className="muted" style={{ fontSize: '10px', fontFamily: 'var(--font-mono)', marginTop: '4px' }}>
            observed = Core saw the output · checked = Core re-ran/re-statted · reviewed = independent Reviewer.
          </div>
        </>
      )}
      {receipt.verifiedOutputs.length === 0 && (
        <div className="muted" style={{ fontSize: '12px', marginTop: '8px' }}>
          No verified outputs recorded. Core did not observe a backing tool call for this mission's claims.
        </div>
      )}

      {hasPartial(receipt) && (
        <>
          <div className="h3" style={{ color: 'var(--danger)', marginTop: '12px' }}>Not completed</div>
          <div className="not-changed">
            <ul>
              {receipt.partialOrFailed.map((p, i) => (
                <li key={i}>step {p.step}: {p.status} — {p.reason}</li>
              ))}
            </ul>
          </div>
        </>
      )}

      <div className="meta-row">
        <span>Model: {receipt.model ?? '—'}</span>
        <span>Provider: {receipt.provider ?? '—'}</span>
        <span>Approvals used: {receipt.approvalsUsed}</span>
        <span>{formatTokens(receipt.tokens)}</span>
        {receipt.independentlyReviewed && <span>Independently reviewed</span>}
      </div>

      <div className="h3">Next action</div>
      <div className="muted" style={{ fontSize: '13px', marginBottom: '10px' }}>{receipt.nextAction ?? 'No further action recorded.'}</div>

      <div className="actions">
        <button className="btn btn-ghost" disabled={!onReviewDiff} onClick={onReviewDiff} title={!onReviewDiff ? 'Not available yet' : undefined}>Review diff</button>
        {receipt.undoAvailable && <button className="btn btn-ghost" disabled={!onUndo} onClick={onUndo} title={!onUndo ? 'Not available yet' : undefined}>{receipt.undoHint ?? 'Undo'}</button>}
        {!confirmShare
          ? <button className="btn btn-ghost" onClick={() => setConfirmShare(true)}>Share (sanitized)</button>
          : <span style={{ display: 'inline-flex', gap: '6px', alignItems: 'center' }}>
              <span className="muted" style={{ fontSize: '11px' }}>Copy sanitized summary?</span>
              <button className="btn btn-primary" style={{ fontSize: '12px', padding: '4px 8px' }} onClick={handleShare}>Copy</button>
              <button className="btn btn-ghost" style={{ fontSize: '12px', padding: '4px 8px' }} onClick={() => setConfirmShare(false)}>Cancel</button>
            </span>}
      </div>
      <div className="muted" style={{ fontSize: '10px', marginTop: '10px', fontFamily: 'var(--font-mono)' }}>
        Share copies only structured fields (counts, status, model, duration, evidence levels). Free-text fields (objective, next action) are excluded. Confirm before copying.
      </div>
    </div>
  );
}