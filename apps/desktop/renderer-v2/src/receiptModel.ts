// Outcome Receipt — the view model for the verified completion card.
//
// Pure functions only. The component (OutcomeReceipt.tsx) renders them; the
// Core receipt (core/runtime/outcomeReceipt.ts) is the source of truth. The
// view model here keeps presentation logic testable without a renderer.

export type EvidenceLevel = 'observed' | 'checked' | 'reviewed';

export interface ReceiptOp { label: string; count: number }
export interface ReceiptArtifact { path: string; bytes: number | null; kind: string; exists: boolean }
export interface ReceiptVerifiedOutput { label: string; level: EvidenceLevel }
export interface ReceiptPartial { step: number; status: string; reason: string }
export interface ReceiptStep {
  idx: number; agentId: string; kind: 'work' | 'review'; title: string;
  status: string; error: string | null; seconds: number | null;
  artifacts: ReceiptArtifact[];
  evidence: { verified: Array<{ tool: string; count: number }>; unbacked: string[]; caveats?: string[] } | null;
}
export interface Receipt {
  missionId: string; objective: string; status: string; headline: string;
  startedAt: string | null; completedAt: string | null; durationMs: number | null;
  steps: ReceiptStep[];
  operations: ReceiptOp[];
  artifacts: ReceiptArtifact[];
  verifiedOutputs: ReceiptVerifiedOutput[];
  partialOrFailed: ReceiptPartial[];
  approvalsUsed: number;
  model: string | null; provider: string | null;
  tokens: { prompt: number; completion: number } | null;
  costUsd: number | null;
  nextAction: string | null;
  undoAvailable: boolean; undoHint: string | null;
  independentlyReviewed: boolean;
}

export type StampKind = 'verified' | 'issues' | 'failed' | 'cancelled' | 'interrupted' | 'running';

export function stampKind(status: string): StampKind {
  if (status === 'completed') return 'verified';
  if (status === 'completed_with_issues') return 'issues';
  if (status === 'failed') return 'failed';
  if (status === 'cancelled') return 'cancelled';
  if (status === 'interrupted') return 'interrupted';
  return 'running';
}

export function stampLabel(kind: StampKind): string {
  switch (kind) {
    case 'verified': return 'Verified';
    case 'issues': return 'Completed with issues';
    case 'failed': return 'Not finished';
    case 'cancelled': return 'Cancelled';
    case 'interrupted': return 'Interrupted';
    case 'running': return 'In progress';
  }
}

export function stampClass(kind: StampKind): string {
  if (kind === 'verified') return 'verified';
  if (kind === 'failed' || kind === 'cancelled') return 'failed';
  return 'attention';
}

export function formatDuration(ms: number | null): string {
  if (ms == null) return '—';
  if (ms < 1000) return `${ms} ms`;
  const s = Math.round(ms / 1000);
  if (s < 60) return `${s}s`;
  const m = Math.floor(s / 60), r = s % 60;
  return r ? `${m}m ${r}s` : `${m}m`;
}

export function formatTokens(t: { prompt: number; completion: number } | null): string {
  if (!t) return '—';
  return `${(t.prompt + t.completion).toLocaleString()} tokens`;
}

export function receiptHeadline(r: Receipt): string {
  return r.objective || 'Untitled task';
}

export function visibleOps(r: Receipt): ReceiptOp[] {
  // Hide zero-count ops; keep a stable, meaningful order.
  const order = ['files changed', 'tests passed', 'checks run', 'commands run', 'research queries', 'organizer actions', 'facts remembered', 'git commits'];
  const map = new Map(r.operations.map((o) => [o.label, o.count]));
  const out: ReceiptOp[] = [];
  for (const label of order) {
    const c = map.get(label);
    if (c && c > 0) out.push({ label, count: c });
  }
  for (const o of r.operations) if (!order.includes(o.label) && o.count > 0) out.push(o);
  return out;
}

export function hasPartial(r: Receipt): boolean {
  return r.partialOrFailed.length > 0;
}

export function shareable(r: Receipt): string {
  // Redacted summary: only structured fields. Free-text (objective, nextAction) excluded.
  const lines: string[] = [];
  lines.push(`Pandesh Outcome Receipt`);
  lines.push(`Status: ${r.headline}`);
  lines.push(`Operations: ${r.operations.map((o) => `${o.count} ${o.label}`).join(', ') || 'none recorded'}`);
  if (r.verifiedOutputs.length) lines.push(`Verified outputs: ${r.verifiedOutputs.map((v) => `${v.label} (${v.level})`).join('; ')}`);
  if (r.partialOrFailed.length) lines.push(`Not completed: ${r.partialOrFailed.map((p) => `${p.status} - ${p.reason}`).join('; ')}`);
  lines.push(`Model: ${r.model ?? '—'} (${r.provider ?? '—'})`);
  lines.push(`Duration: ${formatDuration(r.durationMs)}`);
  lines.push(`Approvals used: ${r.approvalsUsed}`);
  if (r.independentlyReviewed) lines.push('Independently reviewed: yes');
  lines.push('Generated by Pandesh. Free-text fields (objective, next action) excluded; paths, tokens and identifiers redacted.');
  return lines.join('\n');
}