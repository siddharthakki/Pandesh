/**
 * Rasterizes assets/icon.svg into the PNG sizes Windows actually needs and
 * packs them into assets/icon.ico (rcedit / Inno Setup consume the .ico at
 * package time). Also regenerates src/host/appIcon.ts, which embeds the same
 * PNGs as base64 so the running app never has to resolve an asset path
 * across the three different layouts (dev, portable, installed) — same
 * reasoning as the placeholder this replaces in jarvisTray.ts.
 *
 * Run after editing assets/icon.svg:
 *   node apps/desktop/scripts/build-icons.mjs
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from '../../../node_modules/sharp/lib/index.js';

const desktopRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assetsDir = path.join(desktopRoot, 'assets');
const svgPath = path.join(assetsDir, 'icon.svg');
const icoSizes = [16, 32, 48, 256];
const embedSizes = [16, 24, 32, 48, 256];
// Below ~40px the full framed artwork (glow, perimeter nodes, sphere lattice)
// collapses into a dark smudge — a cropped, zoomed-in render of just the
// sphere+eye core stays legible at tray/taskbar sizes. Threshold is inclusive.
const CROP_BELOW = 40;
const CROPPED_VIEWBOX = 'viewBox="78 78 356 356"';
const FULL_VIEWBOX_RE = /viewBox="0 0 512 512"/;

function buildIco(pngsBySize) {
  const entries = icoSizes.map((size) => pngsBySize.get(size));
  const headerSize = 6 + entries.length * 16;
  let offset = headerSize;
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(entries.length, 4);

  const dirEntries = [];
  for (const [i, size] of icoSizes.entries()) {
    const png = entries[i];
    const entry = Buffer.alloc(16);
    entry.writeUInt8(size >= 256 ? 0 : size, 0); // width (0 == 256)
    entry.writeUInt8(size >= 256 ? 0 : size, 1); // height (0 == 256)
    entry.writeUInt8(0, 2); // color count
    entry.writeUInt8(0, 3); // reserved
    entry.writeUInt16LE(1, 4); // planes
    entry.writeUInt16LE(32, 6); // bit count
    entry.writeUInt32LE(png.length, 8); // bytes in resource
    entry.writeUInt32LE(offset, 12); // offset
    offset += png.length;
    dirEntries.push(entry);
  }
  return Buffer.concat([header, ...dirEntries, ...entries]);
}

async function main() {
  fs.mkdirSync(assetsDir, { recursive: true });
  const fullSvg = fs.readFileSync(svgPath, 'utf8');
  if (!FULL_VIEWBOX_RE.test(fullSvg)) throw new Error('icon.svg viewBox is not "0 0 512 512"; update CROPPED_VIEWBOX to match');
  const croppedSvg = fullSvg.replace(FULL_VIEWBOX_RE, CROPPED_VIEWBOX);
  const allSizes = [...new Set([...icoSizes, ...embedSizes, 512])];
  const pngsBySize = new Map();
  for (const size of allSizes) {
    const source = size < CROP_BELOW ? croppedSvg : fullSvg;
    const buf = await sharp(Buffer.from(source), { density: 384 }).resize(size, size).png().toBuffer();
    pngsBySize.set(size, buf);
  }

  fs.writeFileSync(path.join(assetsDir, 'icon.ico'), buildIco(pngsBySize));
  fs.writeFileSync(path.join(assetsDir, 'icon-512.png'), pngsBySize.get(512));
  console.log(`Wrote ${path.join(assetsDir, 'icon.ico')} and icon-512.png`);

  const wrap = (b64) => b64.match(/.{1,100}/g).map((line) => `  '${line}'`).join(' +\n');
  const entries = embedSizes.map((size) => {
    const b64 = pngsBySize.get(size).toString('base64');
    return `  ${size}: (\n${wrap(b64)}\n  ),`;
  }).join('\n');

  const ts = `/**
 * Generated by scripts/build-icons.mjs from assets/icon.svg — do not edit by
 * hand. Embedded (not loaded from disk) so the app icon resolves correctly
 * whether running from source, the portable tree, or an installed copy.
 */
import { nativeImage, type NativeImage } from 'electron';

const ICON_PNG_BASE64: Record<number, string> = {
${entries}
};

export function createAppIcon(): NativeImage {
  const image = nativeImage.createEmpty();
  for (const [size, base64] of Object.entries(ICON_PNG_BASE64)) {
    image.addRepresentation({ width: Number(size), height: Number(size), buffer: Buffer.from(base64, 'base64') });
  }
  return image;
}
`;
  const outPath = path.join(desktopRoot, 'src', 'host', 'appIcon.ts');
  fs.writeFileSync(outPath, ts);
  console.log(`Wrote ${outPath}`);
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
