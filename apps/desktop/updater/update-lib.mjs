/**
 * Pandesh application update: package format, verification and compatibility rules.
 *
 * Shared by the update builder (scripts/build-update-package.mjs) and the installed updater (apply-update.mjs, which
 * ships in the install tree under `updater/` and is never replaced by an update).
 *
 * A package (`*.pdupdate`) is a zip with:
 *   manifest.json   what is inside, the compatibility rules, and the sha256 + size of every file
 *   manifest.sig    base64 Ed25519 signature over the exact bytes of manifest.json
 *   payload/<path>  the files, at their install-relative paths
 *
 * Trust: only a manifest signed by a key listed in updater/update-trust.json is accepted. An update can replace
 * ONLY the managed components below (Core bundle, UI bundle, build identity); it can never touch the Electron
 * runtime, node.exe, models, the updater or its trust file. Those need the installer.
 */
import * as crypto from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { spawnSync } from 'node:child_process';

export const UPDATE_SCHEMA = 1;
export const UPDATER_PROTOCOL = 1;
export const PACKAGE_EXTENSION = '.pdupdate';
export const MAX_PACKAGE_BYTES = 256 * 1024 * 1024;

/** The only install-relative paths an update may write. */
export const COMPONENTS = {
  core: { files: ['runtime/core.js'], dirs: [] },
  ui: { files: ['app/package.json'], dirs: ['app/out', 'app/renderer'] },
};
export const META_FILES = ['build-identity.json'];
/** Regenerated by the updater from the installed files (never shipped in a package). */
export const FINGERPRINT_FILE = 'build-fingerprint.json';

const FINGERPRINT_MANDATORY = {
  coreBundle: 'runtime/core.js',
  nodeRuntime: 'runtime/node.exe',
  mainBundle: 'app/out/main.js',
  preloadBundle: 'app/out/preload.js',
  rendererHtml: 'app/renderer/index.html',
  rendererScript: 'app/renderer/renderer.js',
  appPackageJson: 'app/package.json',
  electronExe: 'electron/electron.exe',
  piAgentCore: 'runtime/node_modules/@earendil-works/pi-agent-core/package.json',
  piAi: 'runtime/node_modules/@earendil-works/pi-ai/package.json',
  whisperConfig: 'models/whisper-base-en/Xenova/whisper-base.en/config.json',
  asrTransformers: 'runtime-assets/node_modules/@xenova/transformers/package.json',
  buildIdentity: 'build-identity.json',
};

export function sha256File(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

export function sha256Bytes(bytes) {
  return crypto.createHash('sha256').update(bytes).digest('hex');
}

export function managedFor(components) {
  const files = new Set(META_FILES);
  const dirs = [];
  for (const name of components) {
    for (const f of COMPONENTS[name].files) files.add(f);
    dirs.push(...COMPONENTS[name].dirs);
  }
  return { files, dirs };
}

export function isManagedPath(rel, components) {
  const { files, dirs } = managedFor(components);
  return files.has(rel) || dirs.some((d) => rel.startsWith(`${d}/`));
}

const RESERVED = /^(con|prn|aux|nul|com\d|lpt\d)(\..*)?$/i;

/** A package path is relative, forward-slashed, made of plain segments, and cannot name a Windows device or stream. */
export function isSafeRelPath(rel) {
  if (typeof rel !== 'string' || !rel || rel.length > 240) return false;
  return rel.split('/').every((seg) => /^[A-Za-z0-9._@+ -]+$/.test(seg)
    && seg !== '.' && seg !== '..' && !/[. ]$/.test(seg) && !RESERVED.test(seg));
}

function tarExe() {
  return path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'tar.exe');
}

function walk(root, rel = '') {
  const out = [];
  for (const entry of fs.readdirSync(path.join(root, rel), { withFileTypes: true })) {
    const childRel = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isSymbolicLink() || (!entry.isDirectory() && !entry.isFile())) {
      throw new Error(`staged package contains a link or special file: ${childRel}`);
    }
    if (entry.isDirectory()) out.push(...walk(root, childRel));
    else out.push(childRel);
  }
  return out;
}

export function readTrust(installRoot) {
  const trust = JSON.parse(fs.readFileSync(path.join(installRoot, 'updater', 'update-trust.json'), 'utf8'));
  if (!Array.isArray(trust.keys) || trust.keys.length === 0) throw new Error('updater has no trusted signing key');
  return trust;
}

/** Lists, validates and extracts a package into an empty staging directory. Nothing is installed. */
export function extractPackage(packagePath, stagingRoot) {
  const stat = fs.statSync(packagePath);
  if (!stat.isFile()) throw new Error('the selected update package is not a file');
  if (stat.size > MAX_PACKAGE_BYTES) throw new Error('the selected update package is too large');
  const listing = spawnSync(tarExe(), ['-tf', packagePath], { encoding: 'utf8', windowsHide: true, maxBuffer: 64 * 1024 * 1024 });
  if (listing.status !== 0) throw new Error('the selected file is not a readable update package');
  const names = listing.stdout.split(/\r?\n/).filter(Boolean);
  if (names.length > 5000) throw new Error('the update package has too many entries');
  for (const raw of names) {
    const name = raw.replace(/\/$/, '');
    const ok = name === 'manifest.json' || name === 'manifest.sig' || name === 'payload'
      || (name.startsWith('payload/') && isSafeRelPath(name.slice('payload/'.length)));
    if (!ok) throw new Error(`the update package contains an unexpected entry: ${raw.slice(0, 80)}`);
  }
  fs.rmSync(stagingRoot, { recursive: true, force: true });
  fs.mkdirSync(stagingRoot, { recursive: true });
  const extract = spawnSync(tarExe(), ['-xf', packagePath, '-C', stagingRoot], { windowsHide: true });
  if (extract.status !== 0) throw new Error('the update package could not be unpacked');
}

/**
 * Verifies a staged (already extracted) package: signature, manifest shape, every payload file's size and sha256, no
 * extra files, only managed paths. Returns the parsed manifest. Throws with a user-readable reason.
 */
export function verifyStaged(stagingRoot, installRoot) {
  const manifestPath = path.join(stagingRoot, 'manifest.json');
  const sigPath = path.join(stagingRoot, 'manifest.sig');
  if (!fs.existsSync(manifestPath) || !fs.existsSync(sigPath)) throw new Error('the update package has no signed manifest');
  const bytes = fs.readFileSync(manifestPath);
  const signature = Buffer.from(fs.readFileSync(sigPath, 'utf8').trim(), 'base64');
  let manifest;
  try { manifest = JSON.parse(bytes.toString('utf8')); } catch { throw new Error('the update manifest is not valid JSON'); }

  const key = readTrust(installRoot).keys.find((k) => k.id === manifest.signingKeyId);
  if (!key) throw new Error('the update is signed with a key this installation does not trust');
  if (!crypto.verify(null, bytes, crypto.createPublicKey(key.publicKeyPem), signature)) {
    throw new Error('the update signature is invalid: the package was altered or is not from the trusted publisher');
  }

  if (manifest.schema !== UPDATE_SCHEMA || manifest.product !== 'pandesh' || manifest.platform !== 'win32-x64') {
    throw new Error('this update is not a Pandesh Windows x64 update this updater understands');
  }
  if (!Number.isInteger(manifest.revision) || manifest.revision <= 0) throw new Error('the update has no valid revision');
  if (!Array.isArray(manifest.components) || manifest.components.length === 0
    || manifest.components.some((c) => !Object.hasOwn(COMPONENTS, c))) {
    throw new Error('the update names an unknown component');
  }
  if (!Array.isArray(manifest.files) || manifest.files.length === 0) throw new Error('the update lists no files');

  const seen = new Set();
  for (const f of manifest.files) {
    if (!isSafeRelPath(f.path) || !isManagedPath(f.path, manifest.components)) throw new Error(`the update tries to write an unmanaged path: ${String(f.path).slice(0, 80)}`);
    if (seen.has(f.path.toLowerCase())) throw new Error(`the update lists a file twice: ${f.path}`);
    seen.add(f.path.toLowerCase());
    if (!Number.isInteger(f.size) || !/^[0-9a-f]{64}$/.test(f.sha256 ?? '')) throw new Error(`the update has a malformed entry for ${f.path}`);
  }
  for (const name of manifest.components) {
    for (const required of COMPONENTS[name].files) if (!seen.has(required)) throw new Error(`the ${name} component is missing ${required}`);
    for (const dir of COMPONENTS[name].dirs) if (![...seen].some((p) => p.startsWith(`${dir}/`))) throw new Error(`the ${name} component has no files under ${dir}`);
  }
  for (const required of META_FILES) if (!seen.has(required)) throw new Error(`the update is missing ${required}`);

  const present = fs.existsSync(path.join(stagingRoot, 'payload')) ? walk(path.join(stagingRoot, 'payload')) : [];
  const unlisted = present.filter((p) => !seen.has(p.toLowerCase()));
  if (unlisted.length) throw new Error(`the update contains files its manifest does not list: ${unlisted[0]}`);
  for (const f of manifest.files) {
    const file = path.join(stagingRoot, 'payload', ...f.path.split('/'));
    if (!fs.existsSync(file) || fs.statSync(file).size !== f.size || sha256File(file) !== f.sha256) {
      throw new Error(`the update is corrupt: ${f.path} does not match its recorded hash`);
    }
  }
  const identity = JSON.parse(fs.readFileSync(path.join(stagingRoot, 'payload', 'build-identity.json'), 'utf8'));
  if (identity.buildNumber !== manifest.revision || identity.version !== manifest.version) {
    throw new Error('the update build identity disagrees with its manifest');
  }
  return manifest;
}

export function readInstalled(installRoot) {
  const identity = JSON.parse(fs.readFileSync(path.join(installRoot, 'build-identity.json'), 'utf8'));
  let electron = null;
  try { electron = fs.readFileSync(path.join(installRoot, 'electron', 'version'), 'utf8').trim().replace(/^v/, ''); } catch { /* unknown */ }
  return { version: identity.version, buildNumber: identity.buildNumber, electron };
}

/**
 * What the OS says about a live process: its executable and creation time. Read-only (one CIM query for one PID).
 * Null when the process is gone or the OS will not disclose it.
 */
export function readProcessIdentity(pid, spawnSyncImpl = spawnSync) {
  if (!Number.isInteger(pid) || pid <= 0) return null;
  try {
    const script = `$p = Get-CimInstance Win32_Process -Filter "ProcessId = ${pid}" -ErrorAction SilentlyContinue; `
      + 'if ($p) { @{ exe = $p.ExecutablePath; created = $(if ($p.CreationDate) { $p.CreationDate.ToUniversalTime().ToString("o") } else { $null }) } | ConvertTo-Json -Compress }';
    const out = spawnSyncImpl('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', script], { encoding: 'utf8', windowsHide: true, timeout: 10_000 });
    const text = String(out?.stdout ?? '').trim();
    if (!text) return null;
    const parsed = JSON.parse(text);
    const creationTimeMs = parsed.created ? Date.parse(parsed.created) : NaN;
    return { executablePath: parsed.exe ? String(parsed.exe) : null, creationTimeMs: Number.isFinite(creationTimeMs) ? creationTimeMs : null };
  } catch {
    return null;
  }
}

/**
 * The updater's force-stop rule. A PID taken from a file (core.json) or remembered from a spawn may by now belong to
 * something else: Windows recycles PIDs, and a copied profile's core.json names another profile's Core. A process may
 * be force-stopped only while it still IS the expected program (same executable) and was created no earlier than
 * `notBeforeMs` (minus a small clock tolerance). Missing identity is a refusal, never a permission.
 */
export function mayForceStop(identity, expectedExecutable, notBeforeMs) {
  if (!identity || !identity.executablePath || identity.creationTimeMs === null || identity.creationTimeMs === undefined) return false;
  if (!Number.isFinite(notBeforeMs)) return false;
  const same = path.resolve(identity.executablePath).toLowerCase() === path.resolve(expectedExecutable).toLowerCase();
  return same && identity.creationTimeMs >= notBeforeMs - 2_000;
}

/** Highest applied Core migration in the user's database, 0 when there is no database yet. */
export async function readDbSchema(dataDir) {
  const file = path.join(dataDir, 'core.db');
  if (!fs.existsSync(file)) return 0;
  const { DatabaseSync } = await import('node:sqlite');
  const db = new DatabaseSync(file, { readOnly: true });
  try {
    return db.prepare('SELECT MAX(version) AS v FROM schema_migrations').get()?.v ?? 0;
  } catch {
    return 0;
  } finally {
    db.close();
  }
}

/**
 * The explicit compatibility rules. Returns the list of reasons the package cannot be applied (empty = compatible)
 * and whether Core will migrate the database on its next start.
 */
export function checkCompat(manifest, installed, dbSchema) {
  const problems = [];
  const compat = manifest.compat ?? {};
  if (manifest.requiresUpdater > UPDATER_PROTOCOL) problems.push('this update needs a newer updater: install the latest Pandesh installer first');
  if (manifest.revision <= installed.buildNumber) problems.push(`this update (b${manifest.revision}) is not newer than the installed build (b${installed.buildNumber})`);
  if (compat.baseVersion !== installed.version) problems.push(`this update is for Pandesh ${compat.baseVersion}, but ${installed.version} is installed: use the installer for a new version`);
  if (!(installed.buildNumber >= compat.installedBuildMin && installed.buildNumber <= compat.installedBuildMax)) {
    problems.push(`this update applies to builds b${compat.installedBuildMin}–b${compat.installedBuildMax}, but b${installed.buildNumber} is installed`);
  }
  if (compat.electron !== installed.electron) problems.push(`this update expects Electron ${compat.electron}, but ${installed.electron ?? 'an unknown version'} is installed: use the installer`);
  if (!Number.isInteger(compat.dbSchemaTarget)) problems.push('the update does not declare its database schema');
  else if (dbSchema > compat.dbSchemaTarget) problems.push(`your data is at database schema ${dbSchema}, newer than this update understands (${compat.dbSchemaTarget}): refusing to downgrade`);
  const migrates = Number.isInteger(compat.dbSchemaTarget) && compat.dbSchemaTarget > dbSchema;
  return { problems, migrates };
}

/** Rewrites build-fingerprint.json from the files actually installed, so smoke checks of the updated tree still hold. */
export function regenerateFingerprint(installRoot, manifest) {
  const file = path.join(installRoot, FINGERPRINT_FILE);
  let previous = {};
  try { previous = JSON.parse(fs.readFileSync(file, 'utf8')); } catch { /* none */ }
  const files = {};
  for (const [name, rel] of Object.entries(FINGERPRINT_MANDATORY)) {
    const full = path.join(installRoot, ...rel.split('/'));
    files[name] = { path: rel, bytes: fs.statSync(full).size, sha256: sha256File(full).toUpperCase() };
  }
  fs.writeFileSync(file, `${JSON.stringify({
    ...previous,
    builtAt: manifest.builtAt,
    commit: manifest.commit,
    sourceState: manifest.sourceState,
    updatedBy: { revision: manifest.revision, at: new Date().toISOString() },
    buildIdentity: JSON.parse(fs.readFileSync(path.join(installRoot, 'build-identity.json'), 'utf8')),
    files,
  }, null, 2)}\n`);
}
